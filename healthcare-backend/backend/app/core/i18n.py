"""
app/core/i18n.py — Centralised i18n translation module.

Supports: en (English), hi (Hindi), ta (Tamil), te (Telugu),
          ml (Malayalam), mr (Marathi), kn (Kannada).

Usage:
    from app.core.i18n import translate, set_language, get_language

    set_language("hi")
    msg = translate("auth.login_successful")
"""
from __future__ import annotations

from contextvars import ContextVar
from typing import Dict

# ── language context (per-request, thread-safe via contextvars) ────────────
_current_language: ContextVar[str] = ContextVar("current_language", default="en")

SUPPORTED_I18N_CODES = {"en", "hi", "ta", "te", "ml", "mr", "kn"}


def set_language(code: str) -> None:
    """Set the language for the current async context."""
    _current_language.set(code if code in SUPPORTED_I18N_CODES else "en")


def get_language() -> str:
    """Return the active language code for this request."""
    return _current_language.get()



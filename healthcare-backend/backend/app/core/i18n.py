# ── translate() helper ───────────────────────────────────────────────────────
def translate(key: str, lang: str | None = None) -> str:
    """Return the translated string for *key* in the active (or given) language.

    Falls back to English if the key/language combination is missing.
    """
    language = lang or get_language()
    entry = TRANSLATIONS.get(key)
    if entry is None:
        return key  # unknown key — return as-is
    return entry.get(language) or entry.get("en") or key


def translate_dict(keys: list[str], lang: str | None = None) -> dict[str, str]:
    """Translate multiple keys at once; returns {key: translated_value}."""
    language = lang or get_language()
    return {k: translate(k, language) for k in keys}
